/** Returns active storefront products only. */
export const getProductBySlug = (slug: string): StoreProduct | undefined =>
  storeProducts.find((product) => product.slug === slug && product.isActive);

/** Returns a fresh array so callers can safely sort it for presentation. */
export const getProductsByCourse = (course: StoreProduct['course']): StoreProduct[] =>
  storeProducts.filter((product) => product.course === course && product.isActive);
